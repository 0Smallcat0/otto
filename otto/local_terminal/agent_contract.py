def agent_action_preflight_payload(root: Path, action_id: str) -> dict[str, Any]:
    """Return a read-only action readiness packet without executing the action."""

    normalized_action_id = str(action_id or "").strip()
    action = next(
        (candidate for candidate in ACTION_CONTRACTS if candidate.action_id == normalized_action_id),
        None,
    )
    doc_path = Path("docs/planning/M21_AGENT_OPERABILITY_CONTRACT.md")
    safety = {
        "read_only": True,
        "action_executed": False,
        "local_mutation_performed": False,
        "external_network": False,
        "credentials_required": False,
        "credentials_exposed": False,
        "secret_values_returned": False,
        "destructive_actions_enabled": False,
        "live_trading": False,
        "broker_mutation": False,
        "real_orders": False,
        "real_balance": False,
        "margin": False,
        "leverage": False,
        "short": False,
        "derivatives_execution": False,
        "installed_source_read": False,
        "branding_assets_copied": False,
        "commercial_copy_copied": False,
    }
    if action is None:
        return {
            "generated_at": _utc_now(),
            "mode": "read_only_action_preflight",
            "action_id": normalized_action_id,
            "status": "unknown_action",
            "allowed_to_attempt": False,
            "allowed_without_confirmation": False,
            "reason": "Action is not listed in the AI Agent contract.",
            "action": {},
            "stop_gates": list(PREFLIGHT_STOP_GATES),
            "evidence": {
                "contract_doc": str(doc_path),
                "contract_doc_exists": (root / doc_path).exists(),
            },
            "safety": safety,
        }

    action_row = asdict(action)
    allowed_without_confirmation = (
        not action.disabled_by_safety and not action.requires_confirmation
    )
    if action.disabled_by_safety:
        status = "disabled_by_safety"
        reason = "Action is present but blocked by the safety contract."
    elif action.requires_confirmation:
        status = "requires_confirmation"
        reason = "Action is present but requires explicit local confirmation before use."
    else:
        status = "ready"
        reason = "Action is listed as available by the AI Agent contract."
    return {
        "generated_at": _utc_now(),
        "mode": "read_only_action_preflight",
        "action_id": action.action_id,
        "status": status,
        "allowed_to_attempt": allowed_without_confirmation,
        "allowed_without_confirmation": allowed_without_confirmation,
        "reason": reason,
        "action": action_row,
        "stop_gates": list(PREFLIGHT_STOP_GATES),
        "evidence": {
            "contract_doc": str(doc_path),
            "contract_doc_exists": (root / doc_path).exists(),
        },
        "safety": safety,
    }


def _selector_rows() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for route in ROUTE_CONTRACTS:
        rows.extend(
            [
                {
                    "route_id": route.route_id,
                    "selector_id": f"{route.route_id}.route_button",
                    "selector": f"[data-testid='{route.route_button_test_id}']",
                    "purpose": "navigate route from shell rail",
                },
                {
                    "route_id": route.route_id,
                    "selector_id": f"{route.route_id}.workspace",
                    "selector": f"[data-testid='{route.workspace_test_id}']",
                    "purpose": "scope route-specific assertions and workflow operations",
                },
            ]
        )
    rows.append(
        {
            "route_id": "global",
            "selector_id": "global.provider_freshness",
            "selector": "[aria-label='Provider freshness']",
            "purpose": "inspect provider/cache state and start bounded public refresh job",
        }
    )
    return rows


def _route_row(route: RouteAgentContract) -> dict[str, Any]:
    row = asdict(route)
    row["state_fields"] = list(route.state_fields)
    row["artifact_roots"] = list(route.artifact_roots)
    row["recommended_actions"] = list(route.recommended_actions)
    row["disabled_actions"] = list(route.disabled_actions)
    return row


def _utc_now() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")
