interface LangState {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
}

const LangContext = createContext<LangState>({
  lang: "zh",
  setLang: () => undefined,
  t: (key) => key
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return window.localStorage.getItem("ft-lang") === "en" ? "en" : "zh";
    } catch {
      return "zh";
    }
  });
  useEffect(() => {
    try {
      window.localStorage.setItem("ft-lang", lang);
    } catch {
      /* private mode */
    }
  }, [lang]);
  const t = (key: string) => (lang === "en" ? EN[key] ?? key : key);
  return <LangContext.Provider value={{ lang, setLang: setLangState, t }}>{children}</LangContext.Provider>;
}

export function useT(): LangState {
  return useContext(LangContext);
}
